// Math functions 
function addition (a,b) {
    return a + b;
}


function subtraction (a,b) {
    return a - b;
}


function multiplication (a,b) {
    return a * b;
}


function division (a,b) {
    if (b === 0) {
        return "Error"
    }

    return a / b;
}


function percentage (a) {
    return a / 100
}
